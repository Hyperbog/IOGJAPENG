#!/usr/bin/env python3
"""Install Japanese trace support into a SNESRecomp *Japanese* scaffold.

Requires the user's exact verified original ROM and a scaffold generated by
snesrecomp/tools/new_project/setup_project.sh (not Babel's USA source tree).
No ROM or generated ROM code is copied into this patch.
"""
from __future__ import annotations
import argparse
import hashlib
from pathlib import Path
import zlib

SHA256 = "7c0380753f976a8e41de92dc78ac76e413e97f0d8610c2d65b0ac31ff24676d0"
SOURCE = ("jp_probe.c", "jp_probe.h", "jp_snesrecomp_adapter.c", "jp_trace_adapter.h")


def verify_rom(p: Path) -> tuple[str, str]:
    raw = p.read_bytes()
    digest = hashlib.sha256(raw).hexdigest()
    crc = f"{zlib.crc32(raw) & 0xffffffff:08x}"
    if (len(raw) != 2097152 or digest != SHA256 or raw[0xFFC0:0xFFD5] != b"GAIA GENSOUKI 1 JPN  "):
        raise ValueError(f"incorrect Japanese ROM (size={len(raw)}, sha256={digest})")
    return crc, digest


def read_identity(p: Path) -> dict[str, str]:
    fields = {}
    for line in p.read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if "=" in line:
            k, v = line.split("=", 1)
            fields[k.strip()] = v.strip().strip('"')
    return fields


def patch_once(txt: str, before: str, after: str, name: str) -> str:
    if after in txt:
        return txt
    if txt.count(before) != 1:
        raise ValueError(f"{name}: scaffold has changed; expected unique marker {before!r}")
    return txt.replace(before, after, 1)


def install(rom: Path, project: Path, src: Path, check: bool = False) -> list[str]:
    crc, sha = verify_rom(rom)
    project = project.resolve()
    source_dir = src.resolve()
    manifest = project / "rom_identity.txt"
    cmake_path, main_path = project / "CMakeLists.txt", project / "src/main.c"
    if not all(p.is_file() for p in (manifest, cmake_path, main_path)):
        raise ValueError("not a SNESRecomp scaffold: rom_identity.txt / CMakeLists.txt / src/main.c required")
    identity = read_identity(manifest)
    if identity.get("expected_sha256", "").lower() != sha or identity.get("expected_crc32", "").lower() != crc:
        raise ValueError("scaffold ROM identity does not match the original Japanese cartridge")
    if identity.get("mapping") != "hirom" or identity.get("region") != "JPN":
        raise ValueError("scaffold mapping/region must be hirom/JPN")
    main = main_path.read_text(encoding="utf-8")
    cmake = cmake_path.read_text(encoding="utf-8")
    # The scaffold's default source list has exactly one generated-stubs source.
    cmake = patch_once(cmake, "    src/gen_stubs.c\n)",
                       "    src/gen_stubs.c\n    src/jp_probe.c\n    src/jp_snesrecomp_adapter.c\n)", "CMakeLists.txt")
    main = patch_once(main, '#include "game_rtl.h"',
                      '#include "game_rtl.h"\n#include "jp_trace_adapter.h"', "src/main.c")
    entry = 'static const SnesDesktopHostGame kGameHost = {'
    before = '''static void jp_trace_before_run_frame(void) { IogJpTraceBegin(); }
static void jp_trace_end_sim_frame(const uint8_t *field, unsigned number) {
    (void)field; (void)number;
    IogJpTraceFrame();
}

''' + entry
    main = patch_once(main, entry, before, "src/main.c")
    main = patch_once(main, '    .game_info           = &kGameInfo,',
                      '    .game_info           = &kGameInfo,\n'
                      '    .before_run_frame    = jp_trace_before_run_frame,\n'
                      '    .end_sim_frame       = jp_trace_end_sim_frame,', "src/main.c")
    new_sources = {}
    for filename in SOURCE:
        path = source_dir / filename
        if not path.is_file():
            raise ValueError(f"missing instrumentation source: {path}")
        new_sources[project / "src" / filename] = path.read_bytes()
    updates = {cmake_path: cmake.encode(), main_path: main.encode(), **new_sources}
    changed = []
    for path, content in updates.items():
        if path.exists() and path.read_bytes() == content:
            continue
        if check:
            changed.append(f"would update {path.relative_to(project)}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
            changed.append(f"updated {path.relative_to(project)}")
    return changed


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--rom", required=True, type=Path)
    p.add_argument("--project", required=True, type=Path)
    p.add_argument("--source", type=Path, default=Path(__file__).resolve().parent)
    p.add_argument("--check", action="store_true", help="validate and report without changing files")
    args = p.parse_args()
    try:
        for line in install(args.rom, args.project, args.source, args.check):
            print(line)
        print("Japanese source integration validated; ROM execution not yet tested")
    except (OSError, ValueError) as exc:
        p.exit(1, f"jp_native_build: {exc}\n")


if __name__ == "__main__":
    main()
